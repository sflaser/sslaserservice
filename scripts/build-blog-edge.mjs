import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { pathToFileURL } from 'node:url';
import vm from 'node:vm';

// Embed only public browser configuration and current templates, never service credentials.
export async function buildBlogEdge(root) {
  const sandbox = { window: {} };
  vm.runInNewContext(await readFile(join(root, 'assets/js/cms-config.js'), 'utf8'), sandbox, { timeout: 1000 });
  const { supabaseUrl, supabaseAnonKey } = sandbox.window.CMS_CONFIG || {};
  if (!supabaseUrl || !supabaseAnonKey) throw new Error('Missing public blog CMS configuration');
  const templates = {
    en: await readFile(join(root, 'blog.html'), 'utf8'),
    es: await readFile(join(root, 'es/blog.html'), 'utf8'),
  };
  const folder = join(root, 'netlify/edge-functions/lib');
  await mkdir(folder, { recursive: true });
  await writeFile(join(folder, 'blog-data.mjs'),
    '// Generated by scripts/build-blog-edge.mjs. Public configuration only.\n' +
    `export const cms = ${JSON.stringify({ supabaseUrl, supabaseAnonKey })};\n` +
    `export const templates = ${JSON.stringify(templates)};\n`);
  console.log('Prepared English/Spanish blog edge templates. Articles are fetched at request time.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  await buildBlogEdge(resolve('.'));
}
